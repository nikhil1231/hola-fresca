# SQL versions of the SQLite functions the apps' queries use, created in the app's own database (run it in
# the schema setup; it's idempotent). json_extract and json_each take text holding JSON and a '$.a.b[0]' path
# and return text, as the apps compare the results with text; group_concat ignores NULLs as SQLite's does;
# max(a, b) / min(a, b) are NULL if either is, as in SQLite (GREATEST/LEAST would ignore the NULL); sum() of
# a comparison counts the true ones.
SQLITE_FUNCTIONS = r"""
CREATE OR REPLACE FUNCTION sqlite_json_path(path text) RETURNS text[] LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN path = '$' THEN '{}'::text[] ELSE
    regexp_split_to_array(regexp_replace(regexp_replace(substr(path, 2), '\[(\d+)\]', '.\1', 'g'), '^\.', ''), '\.')
  END $$;
CREATE OR REPLACE FUNCTION json_extract(doc text, path text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE jsonb_typeof(v) WHEN 'string' THEN v #>> '{}' WHEN 'null' THEN NULL
                              WHEN 'boolean' THEN (CASE WHEN v = 'true'::jsonb THEN '1' ELSE '0' END) ELSE v::text END
  FROM (SELECT doc::jsonb #> sqlite_json_path(path) AS v) x $$;
CREATE OR REPLACE FUNCTION json_each(doc text, path text DEFAULT '$')
  RETURNS TABLE (key text, value text, type text) LANGUAGE sql IMMUTABLE AS $$
  SELECT k, CASE jsonb_typeof(v) WHEN 'string' THEN v #>> '{}' WHEN 'null' THEN NULL ELSE v::text END, jsonb_typeof(v)
  FROM (SELECT doc::jsonb #> sqlite_json_path(path) AS d) x,
       LATERAL (SELECT (o - 1)::text AS k, e AS v FROM jsonb_array_elements(CASE WHEN jsonb_typeof(d) = 'array' THEN d ELSE '[]' END) WITH ORDINALITY AS a(e, o)
                UNION ALL
                SELECT e.key, e.value FROM jsonb_each(CASE WHEN jsonb_typeof(d) = 'object' THEN d ELSE '{}' END) AS e) y $$;
CREATE OR REPLACE FUNCTION sqlite_concat(state text, value text, sep text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN value IS NULL THEN state WHEN state IS NULL THEN value ELSE state || sep || value END $$;
CREATE OR REPLACE FUNCTION sqlite_concat(state text, value text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT sqlite_concat(state, value, ',') $$;
CREATE OR REPLACE AGGREGATE group_concat(text, text) (SFUNC = sqlite_concat, STYPE = text);
CREATE OR REPLACE AGGREGATE group_concat(text) (SFUNC = sqlite_concat, STYPE = text);
CREATE OR REPLACE FUNCTION max(a anycompatible, b anycompatible) RETURNS anycompatible LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN a IS NULL OR b IS NULL THEN NULL ELSE GREATEST(a, b) END $$;
CREATE OR REPLACE FUNCTION min(a anycompatible, b anycompatible) RETURNS anycompatible LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN a IS NULL OR b IS NULL THEN NULL ELSE LEAST(a, b) END $$;
CREATE OR REPLACE FUNCTION sqlite_bool_add(state bigint, value boolean) RETURNS bigint LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN value IS NULL THEN state ELSE coalesce(state, 0) + value::int END $$;
CREATE OR REPLACE AGGREGATE sum(boolean) (SFUNC = sqlite_bool_add, STYPE = bigint);
"""


