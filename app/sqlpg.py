"""sqlpg: a sqlite3-shaped connection to Postgres, for apps moved from SQLite (infra docs/postgres-migration-plan.md).

Canonical copy: ~/infra/lib/sqlpg.py. Apps vendor this file unchanged; fix bugs here and copy it again.

What it keeps from sqlite3, so an app's queries change little:
  - `?` placeholders, and `:name` ones with dict parameters, translated to psycopg's %s / %(name)s
  - rows that work as tuples and by column name (r[0], r['name'], dict(r), r.keys()), like sqlite3.Row
  - `with connect(url) as db:` commits on success and rolls back on an exception; leaving the block also
    hands the connection back to a small pool (so unlike sqlite3, don't use `db` after the block)
  - cursor.lastrowid (an INSERT into a table with an identity/serial column gets RETURNING it), cursor.rowcount,
    db.total_changes
  - INSERT OR IGNORE -> INSERT ... ON CONFLICT DO NOTHING; LIKE -> ILIKE (SQLite's LIKE ignores case);
    an empty IN () (SQLite allows it)
  - INSERT OR REPLACE INTO t (cols) -> ON CONFLICT (primary key) DO UPDATE (other columns reset to defaults)
  - ORDER BY sorts NULLs as SQLite does (first ascending, last descending)
  - executescript() for DDL; integer-only numeric results (SUM of integers) come back as int, not Decimal
  - IntegrityError, OperationalError, Error, like sqlite3's; True/False parameters are sent as 1/0
  - connect(url, autocommit=True) for sqlite3's isolation_level=None, with db.transaction() and db.in_transaction
  - SQLITE_FUNCTIONS: json_extract, json_each, group_concat, max(a,b), min(a,b), sum(bool) as SQL functions
  - boolean results come back as 1/0
  - SharedConnection(url): one long-lived connection with sqlite3's default transaction behaviour (see there)

What it doesn't do (fix in the app's SQL): PRAGMA, SQLite date functions (datetime(), julianday(), strftime()), json_extract, boolean results of
comparisons in SELECT lists (Postgres returns True/False, SQLite 1/0: cast with ::int), comparing a text
column with a number, GROUP BY that leaves bare columns, and ids from INSERT OR IGNORE that inserted nothing.

DDL: write `id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY` for SQLite's `INTEGER PRIMARY KEY`.
Databases on the shared server compare text by code point (builtin C.UTF-8), as SQLite does.
"""
import atexit
import re
import threading

import psycopg
from psycopg.adapt import Loader
from psycopg.types.numeric import Int8Dumper
from psycopg_pool import ConnectionPool

Error = psycopg.Error
IntegrityError = psycopg.IntegrityError
OperationalError = psycopg.OperationalError
DatabaseError = psycopg.DatabaseError

_pools = {}
_pools_lock = threading.Lock()


class _NumericLoader(Loader):
    """numeric -> int when it has no fraction (SUM/AVG of integers), else float, as SQLite returns."""
    def load(self, data):
        s = bytes(data).decode()
        if s in ("NaN", "Infinity", "-Infinity"):
            return float(s)
        return int(s) if "." not in s else float(s)


class _BoolLoader(Loader):
    def load(self, data):
        return 1 if bytes(data) in (b"t", b"\x01") else 0


def _configure(con):
    con.adapters.register_loader("numeric", _NumericLoader)
    # True/False are sent as 1/0, as sqlite3 stores them (the migrated schemas use integer flags), and a
    # boolean result (a comparison in a SELECT list) comes back as 1/0, as SQLite returns it.
    con.adapters.register_dumper(bool, Int8Dumper)
    con.adapters.register_loader("bool", _BoolLoader)


def pool(url, max_size=5):
    with _pools_lock:
        p = _pools.get(url)
        if p is None:
            p = ConnectionPool(url, min_size=0, max_size=max_size, open=True, configure=_configure,
                               kwargs={"options": "-c timezone=UTC"}, name="sqlpg")
            _pools[url] = p
        return p


def close_all():
    with _pools_lock:
        for p in _pools.values():
            p.close()
        _pools.clear()


atexit.register(close_all)


class Row(tuple):
    """sqlite3.Row lookalike: index by position or by column name."""
    __slots__ = ()
    _names = ()

    def __getitem__(self, key):
        if isinstance(key, str):
            try:
                return tuple.__getitem__(self, self._index[key])
            except KeyError:
                raise IndexError(f"No item with that key: {key}") from None
        return tuple.__getitem__(self, key)

    def keys(self):
        return list(self._names)


def _row_class(names):
    index = {}
    for i, n in enumerate(names):
        index.setdefault(n, i)
    return type("Row", (Row,), {"__slots__": (), "_names": tuple(names), "_index": index})


def _row_factory(cursor):
    desc = cursor.description
    if desc is None:
        return tuple
    cls = _row_class([d.name for d in desc])
    return lambda values: cls(values)


_TOKEN = re.compile(r"""('(?:[^']|'')*')|("(?:[^"]|"")*")|(--[^\n]*)|(\?)|(%)|(?<!:):([A-Za-z_]\w*)|\b(LIKE)\b|\b((NOT\s+)?IN\s*\(\s*\))""", re.I)
_OR_IGNORE = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b", re.I)
_cache = {}


def translate(sql, named=False):
    """`?` (or `:name`, when the parameters are a dict) -> psycopg's %s / %(name)s, a literal % -> %%, and
    LIKE -> ILIKE (SQLite's LIKE ignores case), outside quotes and comments; INSERT OR IGNORE -> ON CONFLICT
    DO NOTHING."""
    out = _cache.get((sql, named))
    if out is not None:
        return out

    def sub(m):
        if m.group(4):
            return "%s"
        if m.group(5):
            return "%%"
        if m.group(6):
            return f"%({m.group(6)})s" if named else m.group(0)
        if m.group(7):
            return "ILIKE"   # SQLite's LIKE ignores ASCII case
        if m.group(8):   # SQLite allows an empty IN (): never true, and NOT IN () always true
            return "<> ALL('{}')" if m.group(9) else "= ANY('{}')"
        return m.group(0).replace("%", "%%")   # psycopg reads % inside quotes and comments too
    out = _TOKEN.sub(sub, sql)
    if _OR_IGNORE.match(out):
        out = _OR_IGNORE.sub("INSERT INTO", out, count=1).rstrip().rstrip(";")
        m = re.search(r"\bRETURNING\b", out, re.I)
        out = (out[:m.start()] + "ON CONFLICT DO NOTHING " + out[m.start():]) if m else out + " ON CONFLICT DO NOTHING"
    out = _sqlite_null_order(out)
    if len(_cache) < 2000:
        _cache[(sql, named)] = out
    return out


_ORDER_BY = re.compile(r"\bORDER\s+BY\b", re.I)
_ORDER_END = re.compile(r"\b(LIMIT|OFFSET|FETCH|FOR|UNION|INTERSECT|EXCEPT|ROWS|RANGE|GROUPS|RETURNING|ON|WINDOW)\b", re.I)


def _sqlite_null_order(sql):
    """SQLite sorts NULL as the smallest value: first in ASC, last in DESC. Postgres does the opposite, so
    every ORDER BY term without its own NULLS FIRST/LAST gets SQLite's (in subqueries, windows and
    aggregates too). Works on SQL already translated, so quoted text is skipped by masking it first."""
    masked = re.sub(r"'(?:[^']|'')*'|\"(?:[^\"]|\"\")*\"", lambda m: "\0" * len(m.group(0)), sql)
    if not _ORDER_BY.search(masked):
        return sql
    inserts = []   # (position, text)
    for m in _ORDER_BY.finditer(masked):
        i, depth, start = m.end(), 0, m.end()
        terms = []
        while i < len(masked):
            c = masked[i]
            if c == "(":
                depth += 1
            elif c == ")":
                if depth == 0:
                    break
                depth -= 1
            elif c == "," and depth == 0:
                terms.append((start, i)); start = i + 1
            elif c == ";" and depth == 0:
                break
            elif depth == 0 and c.isalpha() and (i == 0 or not (masked[i - 1].isalnum() or masked[i - 1] == "_")):
                if _ORDER_END.match(masked, i):
                    break
            i += 1
        terms.append((start, i))
        for a, b in terms:
            term = masked[a:b]
            if not term.strip() or re.search(r"\bNULLS\s+(FIRST|LAST)\b", term, re.I):
                continue
            end = len(term.rstrip())
            desc = re.search(r"\bDESC\s*$", term[:end], re.I)
            inserts.append((a + end, " NULLS LAST" if desc else " NULLS FIRST"))
    for pos, text in sorted(inserts, reverse=True):
        sql = sql[:pos] + text + sql[pos:]
    return sql


_INSERT_INTO = re.compile(r'^\s*INSERT\s+INTO\s+("[^"]+"|[\w.]+)', re.I)
_OR_REPLACE = re.compile(r'^\s*INSERT\s+OR\s+REPLACE\s+INTO\s+("[^"]+"|[\w.]+)\s*(?:\(([^)]*)\))?', re.I)
_identity_cache = {}
_replace_cache = {}


def _replace(conn, q):
    """INSERT OR REPLACE INTO t (cols) ... -> INSERT INTO t (cols) ... ON CONFLICT (primary key) DO UPDATE: the
    listed columns take the new values and the others go back to their defaults, as SQLite's REPLACE leaves them.
    (SQLite also replaces on a conflict with any other UNIQUE constraint; here only the primary key counts.)"""
    key = (conn._key, q)
    if key in _replace_cache:
        return _replace_cache[key]
    m = _OR_REPLACE.match(q)
    table = m.group(1)
    with conn._pg.cursor() as c:
        c.execute("SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum=ANY(i.indkey) "
                  "WHERE i.indrelid=to_regclass(%s) AND i.indisprimary", (table,))
        pk = [r[0] for r in c.fetchall()]
        c.execute("SELECT attname FROM pg_attribute WHERE attrelid=to_regclass(%s) AND attnum>0 AND NOT attisdropped "
                  "AND attidentity='' AND attgenerated='' ORDER BY attnum", (table,))
        every = [r[0] for r in c.fetchall()]
    # No column list (INSERT OR REPLACE INTO t VALUES (...)): the values are every column, in order.
    listed = [col.strip().strip('"') for col in m.group(2).split(",")] if m.group(2) else every
    if not pk:
        raise ValueError(f"INSERT OR REPLACE into {table}, which has no primary key")
    sets = [f'"{col}"=EXCLUDED."{col}"' if col in listed else f'"{col}"=DEFAULT' for col in every if col not in pk]
    conflict = "(" + ",".join(f'"{col}"' for col in pk) + ")"
    tail = f" ON CONFLICT {conflict} " + (f"DO UPDATE SET {', '.join(sets)}" if sets else "DO NOTHING")
    out = re.sub(r"^\s*INSERT\s+OR\s+REPLACE\s+INTO", "INSERT INTO", q, count=1, flags=re.I).rstrip().rstrip(";") + tail
    _replace_cache[key] = out
    return out


def _identity_column(conn, table):
    """The table's generated id column (identity or serial), or None. Cached per database."""
    key = (conn._key, table)
    if key in _identity_cache:
        return _identity_cache[key]
    with conn._pg.cursor() as c:
        c.execute("SELECT to_regclass(%s) IS NOT NULL", (table,))
        exists = c.fetchone()[0]
        if not exists:
            return None
        c.execute("SELECT a.attname FROM pg_attribute a WHERE a.attrelid=to_regclass(%s) AND a.attnum>0 "
                  "AND NOT a.attisdropped AND (a.attidentity<>'' OR pg_get_serial_sequence(%s, a.attname) IS NOT NULL) "
                  "ORDER BY a.attnum LIMIT 1", (table, table))
        row = c.fetchone()
    _identity_cache[key] = row[0] if row else None
    return _identity_cache[key]


class Cursor:
    def __init__(self, conn):
        self._conn = conn
        self._cur = conn._pg.cursor(row_factory=_row_factory)
        self._lastrowid = None
        self._hidden = False   # a RETURNING added for lastrowid: the caller sees no result rows
        self._empty = False    # executemany with no rows: rowcount 0, as sqlite3

    def execute(self, sql, params=()):
        q = translate(sql, isinstance(params, dict))
        if _OR_REPLACE.match(q):
            q = _replace(self._conn, q)
        self._conn._before(q)
        params = tuple(params) if params is not None and not isinstance(params, dict) else params
        self._lastrowid = None
        self._hidden = False
        m = _INSERT_INTO.match(q)
        if m and not re.search(r"\bRETURNING\b", q, re.I):
            col = _identity_column(self._conn, m.group(1))
            if col:
                self._cur.execute(q.rstrip().rstrip(";") + f' RETURNING "{col}"', params)
                rows = self._cur.fetchall()
                self._lastrowid = rows[-1][0] if rows else None
                self._hidden = True
                self._after(q)
                return self
        self._cur.execute(q, params)
        self._after(q)
        return self

    def executemany(self, sql, seq):
        seq = [p if isinstance(p, dict) else tuple(p) for p in seq]
        q = translate(sql, bool(seq) and isinstance(seq[0], dict))
        if _OR_REPLACE.match(q):
            q = _replace(self._conn, q)
        self._conn._before(q)
        self._lastrowid = None
        self._hidden = False
        self._empty = not seq
        if not seq:
            return self
        self._cur.executemany(q, seq)
        self._after(q)
        return self

    def _after(self, q):
        n = self._cur.rowcount
        head = q.lstrip()[:7].upper()
        if head.startswith(("INSERT", "UPDATE", "DELETE")) and n > 0:
            self._conn.total_changes += n

    @property
    def lastrowid(self):
        """The id the last single-row INSERT generated (None if it inserted nothing or the table has no id)."""
        return self._lastrowid

    @property
    def rowcount(self):
        return 0 if self._empty else self._cur.rowcount

    @property
    def description(self):
        return None if self._hidden else self._cur.description

    def fetchone(self):
        return self._cur.fetchone() if self.description else None

    def fetchall(self):
        return self._cur.fetchall() if self.description else []

    def fetchmany(self, size=1):
        return self._cur.fetchmany(size) if self.description else []

    def __iter__(self):
        return iter(self.fetchall())

    def close(self):
        self._cur.close()


class Connection:
    """One pooled Postgres connection, one transaction. Use as `with connect(url) as db:`."""

    def __init__(self, url, max_size=5, timeout=10, autocommit=False):
        self._pool = pool(url, max_size)
        self._key = url
        self._pg = self._pool.getconn(timeout=timeout)   # psycopg_pool.PoolTimeout is an OperationalError
        if autocommit:
            self._pg.autocommit = True
        self.total_changes = 0
        self.row_factory = None   # accepted and ignored: rows are always Row

    def cursor(self):
        return Cursor(self)

    def _before(self, q):
        pass

    def execute(self, sql, params=()):
        return Cursor(self).execute(sql, params)

    def executemany(self, sql, seq):
        return Cursor(self).executemany(sql, seq)

    def executescript(self, script):
        with self._pg.cursor() as c:
            c.execute(script)

    def commit(self):
        self._pg.commit()

    def rollback(self):
        self._pg.rollback()

    @property
    def in_transaction(self):
        return self._pg.info.transaction_status != psycopg.pq.TransactionStatus.IDLE

    def transaction(self):
        """An explicit transaction (for autocommit connections); nested ones become savepoints."""
        return self._pg.transaction()

    def close(self):
        if self._pg is not None:
            try:
                self._pg.rollback()
                self._pg.autocommit = False
            finally:
                self._pool.putconn(self._pg)
                self._pg = None

    def __enter__(self):
        return self

    def __exit__(self, kind, value, tb):
        try:
            if kind is None:
                self._pg.commit()
            else:
                self._pg.rollback()
        finally:
            self.close()
        return False

    def __del__(self):
        if getattr(self, "_pg", None) is not None:
            try:
                self.close()
            except Exception:
                pass


_DML = re.compile(r"^\s*(INSERT|UPDATE|DELETE|REPLACE|WITH\b.*\b(INSERT|UPDATE|DELETE)\b)", re.I | re.S)


class SharedConnection(Connection):
    """One long-lived connection that behaves like a sqlite3 connection in its default mode, for apps that keep
    one open for their whole life and share it between threads (`store.conn`):
      - a SELECT on its own runs and is done (no transaction is left open);
      - an INSERT/UPDATE/DELETE outside a transaction opens one, which stays open until commit();
      - `with conn:` commits on success and rolls back on an exception, and the connection stays open.
    If the server drops the connection while no transaction is open, the next statement reconnects."""

    def __init__(self, url, timeout=10):
        self._url, self._timeout = url, timeout
        self._key = url
        self._lock = threading.RLock()
        self._pg = None
        self._open()
        self.total_changes = 0
        self.row_factory = None

    def _open(self):
        self._pg = psycopg.connect(self._url, autocommit=True, connect_timeout=self._timeout,
                                   options="-c timezone=UTC")
        _configure(self._pg)

    def _before(self, q):
        if _DML.match(q) and not self.in_transaction:
            self._pg.execute("BEGIN")

    def _alive(self):
        if self._pg.closed or self._pg.broken:
            self._open()

    def execute(self, sql, params=()):
        with self._lock:
            self._alive()
            return Cursor(self).execute(sql, params)

    def executemany(self, sql, seq):
        with self._lock:
            self._alive()
            return Cursor(self).executemany(sql, seq)

    def executescript(self, script):
        with self._lock:
            self._alive()
            self.commit()   # as sqlite3's executescript: commit first, then run the script as it stands
            with self._pg.cursor() as c:
                c.execute(script)

    def commit(self):
        with self._lock:
            if self._pg is not None and not self._pg.closed and self.in_transaction:
                self._pg.execute("COMMIT")

    def rollback(self):
        with self._lock:
            if self._pg is not None and not self._pg.closed and self.in_transaction:
                self._pg.execute("ROLLBACK")

    def close(self):
        if self._pg is not None and not self._pg.closed:
            self.rollback()
            self._pg.close()

    def __enter__(self):
        return self

    def __exit__(self, kind, value, tb):
        if kind is None:
            self.commit()
        else:
            self.rollback()
        return False

    def __del__(self):
        pass


def connect(url, max_size=5, timeout=10, autocommit=False):
    """autocommit=True: every statement commits by itself, as sqlite3 with isolation_level=None; group
    statements with `with db.transaction():`."""
    return Connection(url, max_size, timeout, autocommit)


def table_columns(db, table):
    """Column names of a table: the Postgres version of [r[1] for r in PRAGMA table_info(t)]."""
    return [r[0] for r in db.execute(
        "SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=? "
        "ORDER BY ordinal_position", (table,))]


