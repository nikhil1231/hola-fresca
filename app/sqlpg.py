def create_test_database(base_url, prefix="test", template=None):
    """A new empty database next to base_url's (TEST_DATABASE_URL: the `tester` role, which may CREATEDB), or a
    copy of `template` (a URL from this function, with no connections open). Returns its URL; drop it with
    drop_test_database."""
    import secrets
    from psycopg.conninfo import make_conninfo
    name = f"{prefix}_{secrets.token_hex(4)}"
    with psycopg.connect(base_url, autocommit=True) as c:
        tmpl = f' TEMPLATE "{template.rsplit("/", 1)[1].split("?")[0]}"' if template else ""
        c.execute(f'CREATE DATABASE "{name}"{tmpl}')
    return make_conninfo(base_url, dbname=name) if "://" not in base_url else _with_db(base_url, name)


def _with_db(url, name):
    head, _, tail = url.rpartition("/")
    return f"{head}/{name}" + (("?" + tail.split("?", 1)[1]) if "?" in tail else "")


def drop_pool(url):
    """Close the pool for url (its connections end)."""
    with _pools_lock:
        p = _pools.pop(url, None)
    if p is not None:
        p.close()


def drop_test_database(base_url, url):
    name = url.rsplit("/", 1)[1].split("?")[0]
    drop_pool(url)
    import time
    for attempt in range(10):   # an autovacuum worker on it can't be ended by a non-superuser: wait for it
        try:
            with psycopg.connect(base_url, autocommit=True) as c:
                c.execute(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')
            return
        except (psycopg.errors.InsufficientPrivilege, psycopg.errors.ObjectInUse):
            if attempt == 9:
                raise
            time.sleep(0.5)
